"""### Corrected `index2word` mapping with offset

We need to account for the special tokens in the IMDB dataset. Indices 0, 1, and 2 are reserved for `<pad>`, `<sos>`, and `<unk>` respectively. Therefore, we add 3 to each word index from the original `word_index` to align it with the integer sequences in `train_data` and `test_data`.
"""

# Create a reversed dictionary where the values become the keys and vice versa,
# accounting for the IMDB dataset's special tokens that are included by keras to handle padding,start of sequence and unknown_tokens
index2word = {
    0: "<pad>",
    1: "<sos>",
    2: "<unk>"
}

# Retrieve the original word_index from imdb
word_index_original = imdb.get_word_index()

# Load index2word with words, applying a +3 shift
for word, index in word_index_original.items():
  index2word[index + 3] = word

